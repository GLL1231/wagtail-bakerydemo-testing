# -*- coding: utf-8 -*-
"""联系表单"""

from pages import 联系表单页


def test_完整填写后提交成功(页面):
    """5 个必填字段都填好，提交后应显示感谢提示"""
    页 = 联系表单页(页面).open()
    页.填写(
        主题="自动化测试提交",
        姓名="测试员",
        邮箱="test@example.com",
        正文="这是一条自动化测试提交，如看到请忽略。",
    )
    页.提交()

    assert 页.提交成功(), f"没有看到提交成功提示；当前页面文字：{页.正文[:200]}"


def test_必填字段留空时提交被拦截(页面):
    """不填任何内容直接提交，应被 HTML5 required 拦截，不出现成功提示"""
    页 = 联系表单页(页面).open()
    页.提交按钮.click()
    页面.wait_for_timeout(800)

    assert not 页.提交成功(), "必填字段为空却提交成功了"


def test_邮箱格式错误时提交被拦截(页面):
    """邮箱填非法格式，应被浏览器校验拦截"""
    页 = 联系表单页(页面).open()
    页.填写(
        主题="邮箱格式测试",
        姓名="测试员",
        邮箱="abc123",          # 不是合法邮箱
        正文="测试邮箱校验",
    )
    页.提交按钮.click()
    页面.wait_for_timeout(800)

    assert not 页.提交成功(), "非法邮箱却提交成功了"

# -*- coding: utf-8 -*-
"""面包列表与详情"""

from pages import 面包列表页


def test_面包列表显示全部11个面包(页面):
    """列表页应展示 11 个面包卡片（与数据库中的数量一致）"""
    页 = 面包列表页(页面).open()

    assert 页.卡数() == 11, f"期望 11 个，实际 {页.卡数()} 个"
    assert 页.面包链接数() == 11, f"期望 11 个面包链接，实际 {页.面包链接数()}"


def test_点击面包能进入详情页(页面):
    """点击列表第一个面包，应跳转到详情页且标题正确"""
    页 = 面包列表页(页面).open()
    列表标题 = 页.打开第一个面包()

    assert "/breads/" in 页面.url, f"没有跳转到详情页，当前：{页面.url}"
    assert 页面.locator("h1").first.inner_text().strip() == 列表标题, (
        f"详情页标题「{页面.locator('h1').first.inner_text()}」"
        f"与列表「{列表标题}」不一致"
    )


def test_面包列表无横向溢出(页面):
    """列表页排版不应出现横向滚动条"""
    页 = 面包列表页(页面).open()
    assert not 页.有横向溢出(), "面包列表页出现了横向滚动条"
